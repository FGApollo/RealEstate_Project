test('ttlCache coalesces concurrent loads, expires entries, respects maxEntries, and invalidates prefixes', async () => {
  const cache = createTtlCache({ maxEntries: 2 });
  let loads = 0;
  const loader = async () => {
    loads += 1;
    await new Promise((r) => setTimeout(r, 15));
    return { value: loads };
  };

  const [a, b] = await Promise.all([
    cache.getOrSet('k:1', 5000, loader),
    cache.getOrSet('k:1', 5000, loader)
  ]);
  assert.equal(loads, 1);
  assert.deepEqual(a, b);

  cache.set('k:2', 'two', 5000);
  cache.set('other:3', 'three', 5000);
  assert.equal(cache.size(), 2); // evicted oldest k:1

  cache.invalidate('k:');
  assert.equal(cache.get('k:2'), undefined);
  assert.equal(cache.get('other:3'), 'three');
});

